#!/usr/bin/env python3
"""Extract cast-only state data from a local DSDA-Doom 0.27.5 source tree."""
import argparse,re,subprocess
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('source',type=Path);a=p.parse_args()
s=(a.source/'info.c').read_text()
rows=re.findall(r'\{SPR_(\w+),\s*(-?\d+),\s*(-?\d+),[^,]+,\s*(S_\w+)[^}]*\},\s*//\s*(S_\w+)',s)
assert rows[0][-1]=='S_NULL'
ids={r[-1]:i for i,r in enumerate(rows)};ids['0']=0
actors=['POSSESSED','SHOTGUY','CHAINGUY','TROOP','SERGEANT','SKULL','HEAD','KNIGHT','BRUISER','BABY','PAIN','UNDEAD','FATSO','VILE','SPIDER','CYBORG','PLAYER']
labels=['ZOMBIEMAN','SHOTGUN GUY','HEAVY WEAPON DUDE','IMP','DEMON','LOST SOUL','CACODEMON','HELL KNIGHT','BARON OF HELL','ARACHNOTRON','PAIN ELEMENTAL','REVENANT','MANCUBUS','ARCH-VILE','THE SPIDER MASTERMIND','THE CYBERDEMON','OUR HERO']
roster=[];needed=set()
for actor,label in zip(actors,labels):
 block=re.search(r'\{\s*// MT_'+actor+r'\b(.*?)\n  \}',s,re.S).group(1)
 fields={k:v.strip() for v,k in re.findall(r'([^,\n]+),?\s*//\s*(\w+)',block)}
 states=[ids[fields[k]] for k in ['seestate','meleestate','missilestate','deathstate']]
 roster.append((label,states,fields['seesound'].removeprefix('sfx_'),fields['deathsound'].removeprefix('sfx_')))
 needed.update(states)
todo=list(needed)
while todo:
 i=todo.pop();n=ids[rows[i][3]]
 if n not in needed:needed.add(n);todo.append(n)
# Sound cues belong to the cast ticker, never the world actions in these states.
f=(a.source/'f_finale.c').read_text();chunk=f[f.index('// sound hacks'):f.index('if (sfx)',f.index('// sound hacks'))];cues={}
for states,cue in re.findall(r'((?:\s*case S_\w+:)+)\s*sfx = sfx_(\w+);',chunk):
 for state in re.findall(r'S_\w+',states):cues[ids[state]]=cue
out=['// Code generated by scripts/generate_finale_cast.py; DO NOT EDIT.','// Cast-only factual state data from Doom/DSDA 0.27.5 info.c and f_finale.c.','package sessionflow','','var castActors = [...]castActor{']
for label,states,see,death in roster:out.append(f'{{"{label}", {", ".join(map(str,states))}, "{see}", "{death}"}},')
out+=['}','', 'var castStates = map[int]castStateDef{']
for i in sorted(needed):
 sprite,frame,tics,nxt,name=rows[i];out.append(f'{i}: {{"{sprite}", {int(frame)&32767}, {tics}, {ids[nxt]}, "{cues.get(i, "")}"}}, // {name}')
out+=['}'];Path('internal/sessionflow/finale_cast_data.go').write_text('\n'.join(out)+'\n')
subprocess.run(['gofmt','-w','internal/sessionflow/finale_cast_data.go'],check=True)
print(len(needed),'cast states')
